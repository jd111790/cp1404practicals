try:
    numerator = int(input("Enter the numerator: "))
    denominator = int(input("Enter the denominator: "))
    while denominator == 0:
        print("Enter a denominator other than 0 (we cant divide that)")
        denominator = int(input("Enter the denominator: "))
    fraction = numerator / denominator
    print(fraction)
except ValueError:
    print("Numerator and denominator must be valid numbers!")
except ZeroDivisionError:
    print("Cannot divide by zero!")
print("Finished.")

# 1. a value error will occur when a non integer is inputted
# 2. when the program attempts to divide a number by 0
# 3. loop that asks for a denominator input until the input is not 0
